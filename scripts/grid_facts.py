#!/usr/bin/env python3
"""grid_facts.py — print a markdown "Grid facts" section for a grid2op env,
from env introspection (no hand-written numbers).

    .venv/bin/python scripts/grid_facts.py l2rpn_idf_2023 > docs/grid_facts/l2rpn_idf_2023.md

The typical healthy-step reward comes from do-nothing steps on chronics 0-2
(seed 0) while every line is up; the first line-down step per chronic is reported.
"""
from __future__ import annotations
import argparse, re, warnings

import numpy as np


def _fmt(x, nd=1):
    return f"{float(x):.{nd}f}"


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def _ordinal(n):
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"


def facts(env_name, n_steps=12):
    warnings.filterwarnings("ignore")
    import grid2op
    env = grid2op.make(env_name)
    p = env.parameters
    kw = env.get_kwargs()
    L = [f"## Grid facts: `{env_name}`", "",
         f"_Generated by `scripts/grid_facts.py {env_name}` (grid2op {grid2op.__version__})._", ""]

    # ---- size / time ----
    # NOTE: deliberately no episode / chronic length (max_step): the agent must
    # not learn the horizon from the docs (see SIM_HIDE_HORIZON in the backend)
    try:
        n_chronics = len(env.chronics_handler.real_data.subpaths)
    except Exception:
        n_chronics = "?"
    L += ["### Size and time", "",
          f"- substations: **{env.n_sub}** · lines: **{env.n_line}** · generators: **{env.n_gen}** · "
          f"loads: **{env.n_load}** · storage units: **{env.n_storage}**",
          f"- step length: **{env.delta_time_seconds / 60.0:g} min**; scenarios (chronics) available: {n_chronics}",
          ""]

    # ---- names ----
    pat = re.compile(r"^(\d+)_(\d+)_(\d+)$")
    bad, swapped = [], []
    for i, n in enumerate(env.name_line):
        m = pat.match(str(n))
        o, e = int(env.line_or_to_subid[i]), int(env.line_ex_to_subid[i])
        if m and (int(m[1]), int(m[2]), int(m[3])) == (e, o, i):
            swapped.append(f"`{n}` (or=sub_{o}, ex=sub_{e})")
        elif not m or (int(m[1]), int(m[2]), int(m[3])) != (o, e, i):
            bad.append(f"`{n}`")
    L += ["### Names", "",
          "- line names are `<or_sub>_<ex_sub>_<line_id>`: e.g. `"
          + str(env.name_line[0]) + "` joins substation "
          + f"{int(env.line_or_to_subid[0])} (origin, `or`) to {int(env.line_ex_to_subid[0])} (extremity, `ex`). "
          + ("Verified for every line." if not (bad or swapped) else
             "Exceptions"
             + (f" — names with the two subs in the other order: {', '.join(swapped)}" if swapped else "")
             + (f" — names not matching the pattern: {', '.join(bad[:10])}" if bad else "")
             + "; the `or`/`ex` fields in `observe --detailed` are authoritative."),
          f"- substations: `{env.name_sub[0]}` … `{env.name_sub[-1]}`; generators e.g. "
          f"`{env.name_gen[0]}`, `{env.name_gen[-1]}`; loads e.g. `{env.name_load[0]}`",
          ""]

    # ---- reward ----
    rewards, notes = [], []
    for chron in range(3):
        obs = env.reset(seed=0, options={"time serie id": chron})
        for _ in range(n_steps):
            obs, r, done, info = env.step(env.action_space())
            down = int((~obs.line_status).sum())
            if down:
                notes.append(f"chronic {chron} t={int(obs.current_step)}: {down} line(s) down")
                break
            rewards.append(float(r))
            if done:
                break
    rc = type(env._reward_helper.template_reward).__name__
    other = {k: (v.__name__ if isinstance(v, type) else type(v).__name__)
             for k, v in (kw.get("other_rewards") or {}).items()}
    lo, hi = env.reward_range
    L += ["### Reward", "",
          f"- reward class: **{rc}** (range {_fmt(lo)} … {_fmt(hi)})"
          + (f"; extra rewards in `info`: {', '.join(f'{k}={v}' for k, v in other.items())}" if other else ""),
          (f"- typical healthy step (do-nothing, chronics 0-2, all lines up): **≈ {np.mean(rewards):.1f}** "
           f"(min {min(rewards):.1f}, max {max(rewards):.1f}, n={len(rewards)})" if rewards
           else "- typical healthy step: no all-lines-up do-nothing step observed"),
          ]
    if notes:
        L.append("- do-nothing is not always calm (first line-down step per chronic): " + "; ".join(notes))
    L.append("")

    # ---- protections / cooldowns ----
    L += ["### Protections, cooldowns, limits", "",
          f"- overload protection (NB_TIMESTEP_OVERFLOW_ALLOWED={p.NB_TIMESTEP_OVERFLOW_ALLOWED}): a line with "
          f"rho > {p.SOFT_OVERFLOW_THRESHOLD:g} trips on its **{_ordinal(p.NB_TIMESTEP_OVERFLOW_ALLOWED + 1)} consecutive "
          f"overloaded step** — you see it overloaded in {p.NB_TIMESTEP_OVERFLOW_ALLOWED} observations "
          f"({p.NB_TIMESTEP_OVERFLOW_ALLOWED} acts to fix it); rho > {p.HARD_OVERFLOW_THRESHOLD:g} trips at once",
          f"- a tripped line can be reconnected after **{p.NB_TIMESTEP_RECONNECTION}** steps",
          f"- cooldown after acting: line **{p.NB_TIMESTEP_COOLDOWN_LINE}** steps, substation **{p.NB_TIMESTEP_COOLDOWN_SUB}** steps",
          f"- per action: at most **{p.MAX_LINE_STATUS_CHANGED}** line status change(s) and **{p.MAX_SUB_CHANGED}** substation(s) changed",
          f"- action keys this env accepts: {', '.join(f'`{k}`' for k in sorted(env.action_space.actionClass.authorized_keys))}",
          ""]

    # ---- generators ----
    redisp = [i for i in range(env.n_gen) if env.gen_redispatchable[i]]
    L += ["### Redispatchable generators", "",
          f"{len(redisp)} of {env.n_gen} generators accept `redispatch` (ΔMW per step must fit the ramp):", ""]
    L += _table(["gen", "type", "sub", "pmin MW", "pmax MW", "ramp up MW/step", "ramp down MW/step"],
                [(f"`{env.name_gen[i]}`", env.gen_type[i], int(env.gen_to_subid[i]), _fmt(env.gen_pmin[i]),
                  _fmt(env.gen_pmax[i]), _fmt(env.gen_max_ramp_up[i]), _fmt(env.gen_max_ramp_down[i]))
                 for i in redisp])
    ren = [i for i in range(env.n_gen) if env.gen_renewable[i]]
    L += ["", "### Curtailable (renewable) generators", "",
          f"{len(ren)} renewable generators accept `curtail` (cap as a fraction of pmax):", ""]
    L += _table(["gen", "type", "sub", "pmax MW"],
                [(f"`{env.name_gen[i]}`", env.gen_type[i], int(env.gen_to_subid[i]), _fmt(env.gen_pmax[i]))
                 for i in ren])
    if env.n_storage:
        L += ["", "### Storage", ""]
        L += _table(["storage", "sub", "Emax MWh", "max charge MW", "max discharge MW"],
                    [(f"`{env.name_storage[i]}`", int(env.storage_to_subid[i]), _fmt(env.storage_Emax[i]),
                      _fmt(env.storage_max_p_prod[i]), _fmt(env.storage_max_p_absorb[i]))
                     for i in range(env.n_storage)])
    L.append("")

    # ---- opponent ----
    oc = kw.get("opponent_class")
    oc_name = oc.__name__ if isinstance(oc, type) else type(oc).__name__
    L += ["### Opponent", ""]
    if oc_name in ("BaseOpponent", "DontAct", "NoneType") or not oc:
        L.append("- none (no built-in opponent)")
    else:
        ok = kw.get("kwargs_opponent") or {}
        L += [f"- class: **{oc_name}** (attacks with `{kw['opponent_action_class'].__name__}`: it disconnects lines)",
              f"- budget: initial {kw.get('opponent_init_budget')}, +{float(kw.get('opponent_budget_per_ts')):.3g} per step; "
              f"attack_duration cap {kw.get('opponent_attack_duration')} steps, cooldown {kw.get('opponent_attack_cooldown')}"]
        for k, v in ok.items():
            if k != "lines_attacked":
                L.append(f"- `{k}`: {v}")
        la = ok.get("lines_attacked") or []
        if la and isinstance(la[0], (list, tuple)):
            L.append(f"- attackable lines ({len(la)} areas, one opponent per area):")
            L += [f"  - area {k}: " + ", ".join(f"`{n}`" for n in area) for k, area in enumerate(la)]
        elif la:
            L.append("- attackable lines: " + ", ".join(f"`{n}`" for n in la))
        L.append("- in the state an attacked line just shows `status: down` (no attack flag); the "
                 "`simctl act`/`step` JSON `verbose.opponent_attack_line` lists attacked line names. "
                 "Reconnecting it during the attack is overridden by the opponent.")
    L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("env")
    ap.add_argument("--steps", type=int, default=12, help="do-nothing steps for the reward estimate")
    a = ap.parse_args()
    print(facts(a.env, a.steps))
